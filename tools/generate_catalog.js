// generate_catalog.js
//
// Builds docs/catalog.md from the compiled graph (dataform compile --json): every table, view,
// incremental, operation and assertion, grouped by dataset, with description, tags, number of
// documented columns and upstream dependencies. The descriptions live in the models, so the
// catalog is never out of date (just run it again).
//
// usage (from tools/): npm run catalog

const fs = require("fs");
const path = require("path");

const input = process.argv[2] || path.join(__dirname, "out", "compiled.json");
const output = process.argv[3] || path.join(__dirname, "..", "docs", "catalog.md");

const raw = fs.readFileSync(input, "utf8");
const graph = JSON.parse(raw.slice(raw.indexOf("{")));

function kindOf(action, group) {
  if (group === "assertions") return "assertion";
  if (group === "operations") return action.hasOutput ? "operation (table)" : "operation";
  return action.type || "table";
}

const rows = [];
for (const group of ["tables", "operations", "assertions"]) {
  for (const action of graph[group] || []) {
    const descriptor = action.actionDescriptor || {};
    rows.push({
      schema: action.target.schema,
      name: action.target.name,
      kind: kindOf(action, group),
      description: (descriptor.description || "").replace(/\s+/g, " ").replace(/\|/g, "/").trim(),
      columns: (descriptor.columns || []).length,
      deps: (action.dependencyTargets || []).length,
      tags: (action.tags || []).filter(t => t !== "daily"),
      disabled: Boolean(action.disabled),
      file: (action.fileName || "").replace(/\\/g, "/")
    });
  }
}

const bySchema = {};
rows.forEach(r => (bySchema[r.schema] = bySchema[r.schema] || []).push(r));
const schemas = Object.keys(bySchema).sort();

const enabled = rows.filter(r => !r.disabled);
const lines = [];
lines.push("<!-- author: Francisco Lucas / Nikola Wissenklaus / Chico -->");
lines.push("");
lines.push("# catalog");
lines.push("");
lines.push("Generated by `tools/generate_catalog.js` from the compiled graph, do not edit by hand.");
lines.push(`Optional modules OFF in this compilation show up as *(off)*. ${rows.length} actions, ${enabled.length} enabled.`);
lines.push("");
lines.push("| dataset | actions | tables / views / incrementals | operations | assertions |");
lines.push("|---|---|---|---|---|");
schemas.forEach(s => {
  const list = bySchema[s];
  const count = test => list.filter(test).length;
  lines.push(`| [${s}](#${s}) | ${list.length} | ${count(r => ["table", "view", "incremental"].includes(r.kind))} | ${count(r => r.kind.startsWith("operation"))} | ${count(r => r.kind === "assertion")} |`);
});
lines.push("");

schemas.forEach(s => {
  lines.push(`## ${s}`);
  lines.push("");
  lines.push("| name | kind | what it is | cols | deps |");
  lines.push("|---|---|---|---|---|");
  bySchema[s]
    .sort((a, b) => a.name.localeCompare(b.name))
    .forEach(r => {
      const name = `\`${r.name}\`${r.disabled ? " *(off)*" : ""}`;
      lines.push(`| ${name} | ${r.kind} | ${r.description || "-"} | ${r.columns || ""} | ${r.deps} |`);
    });
  lines.push("");
});

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, lines.join("\n"), "utf8");
console.log(`catalog written: ${output} (${rows.length} actions in ${schemas.length} datasets)`);
